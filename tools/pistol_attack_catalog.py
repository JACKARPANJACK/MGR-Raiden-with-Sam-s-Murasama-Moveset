"""Humanoid-only source selection, stable native IDs, and attack-only routes."""
from pathlib import Path
import json
from collections import Counter

ATTACKS = ('pistol_attack01', 'pistol_attack01_down', 'down_shot',
           'melee_combat_01_1p', 'melee_combat_02_1p', 'melee_combat_03_1p',
           'melee_combat_04_1p', 'throw_pistol')
AUXILIARY = ('contact', 'melee_combat_01_2p', 'melee_combat_02_2p',
             'melee_combat_03_2p', 'melee_combat_04_2p')
CLIPS = []
for playable, families in ((True, ATTACKS), (False, AUXILIARY)):
    for inplace in (True, False):
        for family in families:
            source = family + ('_inplace' if inplace else '')
            CLIPS.append(dict(family=family, source=source, inplace=inplace,
                playable=playable, role='attack' if playable else 'contact-gesture' if family=='contact' else 'paired-victim',
                code=f'{0x2f50+len(CLIPS):04x}',
                sourcePath='Assets/InsanePistolAction_AnimSet/Animation/Humanoid/' +
                           ('inplace/' if inplace else '') + source+'.fbx'))
PLAYER_CLIPS = [c for c in CLIPS if c['playable']]
# In-place and root-motion sources are both represented. Runtime travel stays
# actor-owned, while the source's turns, vertical motion and body poses survive.
ROUTES = {'Forward': (0,3,6,8,11,14), 'Back': (1,2,9,10),
          'Left': (4,5,7,12,13,15), 'Right': (6,3,0,14,11,8)}
RATES = (1.18,1.18,1.20,1.30,1.30,1.30,1.35,1.25)
BLENDS = (6,6,12,8,8,8,8,8)


def write_header(repo):
    lines = ['#pragma once', '// Generated by tools/pistol_attack_catalog.py; Humanoid sources only.',
             'namespace PistolAttackCatalog {', 'struct Entry {const char* code; const char* source; float rate; unsigned blend;};',
             'inline constexpr Entry Clips[] = {']
    lines += [f'    {{"{c["code"]}","{c["source"]}",{RATES[i%8]:.2f}f,{BLENDS[i%8]}}},' for i,c in enumerate(PLAYER_CLIPS)]
    lines += ['};', 'inline constexpr unsigned Count=sizeof(Clips)/sizeof(Clips[0]);']
    for direction, route in ROUTES.items():
        lines += [f'inline constexpr unsigned {direction}[] = {{'+','.join(map(str,route))+'};']
    lines += ['}', '']
    (Path(repo)/'PistolAttackCatalog.generated.h').write_text('\n'.join(lines))


def write_coverage(repo):
    repo=Path(repo);out=repo/'local_assets/pistol-unity'
    inventory=json.loads((out/'package-inventory.json').read_text())
    report=json.loads((out/'retarget-report.json').read_text())
    exported={c['sourcePath']:c for c in report['clips']}
    assert set(exported)=={c['sourcePath'] for c in CLIPS}
    rows=[]
    for record in inventory['files']:
        row=dict(record)
        if record['rigType']=='generic':status='excluded-generic-user-preference'
        elif record['rigType']=='mesh':status='excluded-mesh'
        elif record['path'] in exported:
            clip=exported[record['path']]
            assert record['sha256']==clip['sha256']
            status='runtime-attack' if clip['playable'] else 'auxiliary-'+clip['role']
            row.update(code=clip['code'],frames=clip['frames'],sourceAttackRange=clip['sourceAttackRange'])
        elif record['attackCandidate']:raise AssertionError('Missing Humanoid retarget: '+record['path'])
        elif record['family'].lower().startswith('t-pose'):status='reference-bind-calibration'
        else:status='excluded-non-attack'
        row['disposition']=status;rows.append(row)
    counts=dict(Counter(r['disposition'] for r in rows))
    assert len(rows)==150 and counts['runtime-attack']==16 and counts['excluded-non-attack']==48
    (out/'fbx-coverage.json').write_text(json.dumps(dict(totalFbx=len(rows),counts=counts,files=rows),indent=2)+'\n')
    source_frames=sum(c['frames'] for c in report['clips'])
    body_frames=3*sum(c['frames']+12 for c in report['clips'] if c['playable'])
    lines=['# Pistol FBX coverage','',
        'All 150 package FBXs were inventoried. Retarget sources are exclusively from `Animation/Humanoid`. ',
        'The runtime bank contains 16 player attacks: eight attack families, each with its in-place and root-motion source variant. ',
        'Root travel remains actor-owned; authored body turns and vertical movement are retained.','',
        '| Humanoid family | In-place code | Root-motion source code | Destination |',
        '| --- | --- | --- | --- |']
    for family in (*ATTACKS,*AUXILIARY):
        pair=[next(c for c in CLIPS if c['family']==family and c['inplace']==ip) for ip in (True,False)]
        destination='wp2062.dat: directional combos' if pair[0]['playable'] else 'Local auxiliary review bank; excluded from player combos'
        lines.append(f'| {family} | {pair[0]["code"]} | {pair[1]["code"]} | {destination} |')
    lines += ['', 'The eight paired `2p` motions animate the opponent. Both `contact` variants are retained as auxiliary gestures. ',
        'They are retargeted into `local_assets/pistol-unity/paired-and-contact-review.dat`, separately from the installed attack bank.','',
        'The 48 other Humanoid FBXs are non-attack idle, ready, equip, reload, pickup and locomotion clips; the Humanoid T-pose supplies the bind-calibration reference. ',
        'The 74 Generic FBXs and the mesh FBX are excluded. Per-file hashes and dispositions are in `local_assets/pistol-unity/fbx-coverage.json`.','',
        'Direction + C/LB starts one attack. A single buffered follow-up can change direction; repeated taps refresh it. Route variation advances across combos so all 16 attacks can be reached. ',
        'C+LMB / LB+RT retains regular shooting priority. Shot cues follow each clip and use the final animated muzzle direction.','',
        'Paired victim reactions and prop-throw gameplay are not implemented by retargeting the player body motion. ',
        'The pistol-throw body animation is used with the held pistol and the existing projectile volley system.','',
        'Validation: complete native MOT and full-body matrix agreement for every exported frame, continuous rotations, rigid skin twists, ',
        f'Humanoid T-pose bind checks, no added source-rotation jumps across {source_frames:,} frames, valid BXM attack/recovery spans, original pose/grip/attack byte preservation, route coverage, and {body_frames:,} full-body playback frames at three costume scales, including entry and interstage blends. ',
        'The full-body source poses were observed in game in the previous build. The responsive timing profile still requires an in-game feel check.','']
    (repo/'docs/PISTOL_FBX_COVERAGE.md').write_text('\n'.join(lines))
    print('FBX coverage:',counts)


if __name__=='__main__':
    root=Path(__file__).resolve().parents[1];write_header(root)
    if (root/'local_assets/pistol-unity/retarget-report.json').exists():write_coverage(root)
