"""Pack runtime animation bundles as DAT archives, without extracting at runtime."""
import hashlib
import json
from pathlib import Path
import re
from assets import dat_entries
from pistol_attack_catalog import PLAYER_CLIPS
from merge_sam_bodies import pack_members
import shutil

ROOT = Path(__file__).resolve().parents[1]
BANKS = {'StealthAnims': 'pl1c00', 'SamTemplateAnims': 'pl1c10', 'BaseMoveset': 'pl1c20'}
POSE_NAMES = ('crouch_idle','crouch_walk','prone_idle','prone_walk',
 'dive_forward','dive_fall','roll_left_start','roll_left','roll_left_end',
 'roll_right_start','roll_right','roll_right_end','crouch_rifle','prone_rifle',
 'crouch_rpg','standing_grenade','prone_grenade','cqc_miss','cqc_combo1',
 'cqc_combo2','cqc_combo3','cqc_combo4','cqc_grab','cqc_hold','cqc_low_grab',
 'cqc_low_hold','cqc_throw_f','cqc_throw_b','cqc_throw_l','cqc_throw_r',
 'cqc_knife','cqc_low_knife','prone_to_crouch','crouch_grenade')
CQC_NAMES = ('cqc_miss','cqc_combo1','cqc_combo2','cqc_combo3','cqc_combo4',
 'cqc_grab','cqc_hold','cqc_low_grab','cqc_low_hold','cqc_throw_f','cqc_throw_b',
 'cqc_throw_l','cqc_throw_r','cqc_knife','cqc_low_knife','prone_to_crouch')

def member_names(bundle):
    if bundle == 'StealthAnims':
        names = {name+'.gwm': f'pl1c00_{0xd000+i:04x}.gwm' for i,name in enumerate(POSE_NAMES)}
        for i,name in enumerate(CQC_NAMES):
            code = (ROOT/'Release/StealthAnims'/(name+'.mot')).read_bytes()[31:35].decode('ascii')
            assert code == f'{0x2f21+i:04x}'
            for suffix in ('.mot','_seq.bxm','_timing.bin'):
                names[name+suffix] = 'pl1c00_'+code+suffix.replace('_seq.bxm','_0_seq.bxm')
        return names
    if bundle == 'SamTemplateAnims':
        names = {}
        for path in (ROOT/'Release'/bundle).iterdir():
            if path.suffix not in ('.mot','.bxm'): continue
            kind,tail = path.name.split('_',1)
            prefix = {'attacker':'pl1c10','victim':'pl1c11','light':'pl1c12'}[kind]
            names[path.name] = prefix+'_'+tail.replace('_seq.bxm','_0_seq.bxm')
        assert len(names) == 28
        return names
    return {'monsoon_kick.mot':'pl1c20_2f00.mot','monsoon_kick_seq.bxm':'pl1c20_2f00_0_seq.bxm'}


def write_header():
    lines = ['#pragma once', '// Generated by tools/pack_animation_banks.py.', 'namespace AnimationArchiveNames {']
    lines += ['inline constexpr const char* StealthPoses[] = {']
    lines += [f'    "pl1c00_{0xd000+i:04x}.gwm",' for i in range(34)]
    lines += ['};','inline constexpr const char* CqcBases[] = {']
    lines += [f'    "pl1c00_{0x2f21+i:04x}",' for i in range(16)]
    lines += ['};','struct Mapping {const char* folder; const char* source; const char* packed;};',
              'inline constexpr Mapping Members[] = {']
    for bundle in BANKS:
        lines += [f'    {{"{bundle}","{source}","{target}"}},' for source,target in member_names(bundle).items()]
    lines += ['};','}']
    (ROOT/'AnimationArchiveNames.generated.h').write_text('\n'.join(lines)+'\n')


def expected_files(bundle):
    folder = ROOT / 'Release' / bundle
    if bundle == 'StealthAnims':
        names = set(member_names(bundle))
        assert len(names) == 82
    else:
        names = {p.name for p in folder.iterdir() if p.suffix in ('.mot', '.bxm')}
        assert len(names) == (28 if bundle == 'SamTemplateAnims' else 2)
        for name in names:
            if name.endswith('.mot'):
                assert name[:-4]+'_seq.bxm' in names
    mapping = member_names(bundle)
    return {mapping[n]: (folder/n).read_bytes() for n in sorted(names)}

def main():
    output = ROOT/'Release/GameData/pl'
    output.mkdir(parents=True, exist_ok=True)
    write_header()
    manifest = []
    for bundle, archive in BANKS.items():
        members = expected_files(bundle)
        packed = pack_members(members)
        assert dict(dat_entries(packed)) == members
        target = output/(archive+'.dat')
        target.write_bytes(packed)
        manifest.append(dict(path='pl/'+target.name, sha256=hashlib.sha256(packed).hexdigest(),
                             members={n: hashlib.sha256(b).hexdigest() for n,b in members.items()}))
        print(f'PASS: {target.name}: {len(members)} members, {len(packed):,} bytes; exact round trip')
    # Existing handgun poses use the same native naming convention.
    pistol = ROOT/'Release/GameData/wp/wp2062.dat'
    if pistol.exists():
        original = dict(dat_entries(pistol.read_bytes()))
        names = {f'pistol_{name}.gwm': f'wp2062_{0x2f40+i:04x}.gwm' for i,name in enumerate(('ready','raise','lower','crouch','prone'))}
        names['pistol_grip.bin'] = 'wp2062_grip.bin'
        members = {names.get(n,n): b for n,b in original.items()}
        attacks={f'wp2062_{code}{suffix}' for code in (c['code'] for c in PLAYER_CLIPS) for suffix in ('.mot','.gwm','_0_seq.bxm','_timing.bin')}
        assert set(names.values())<=set(members)
        assert set(members)<=set(names.values())|attacks
        packed=pack_members(members)
        assert dict(dat_entries(packed))==members
        pistol.write_bytes(packed)
        print(f'PASS: wp2062.dat: {len(members)} handgun pose/grip/attack members preserved')
    # Retire only the former named staging archives, keeping recoverable copies.
    for name in ('stealth_anims.dat','sam_template_anims.dat','base_moveset_anims.dat'):
        old=output/name
        if old.exists():
            saved=ROOT/'Release/legacy-animation-banks'/name
            saved.parent.mkdir(parents=True,exist_ok=True)
            shutil.move(str(old),str(saved))
    (ROOT/'Release/animation-banks-manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')

if __name__ == '__main__':
    main()
